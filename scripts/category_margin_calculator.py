def calculate_category_margin():
    """
    计算每月品类毛利率
    
    注意：品类维度的销售成本数据需要从数据库/API获取
    当前使用品类回收金额占比 × 月度总成本 近似估算
    """
    
    # 合并所有品类数据
    all_categories = category_jan + category_feb + category_mar
    
    # 按月份分组
    monthly_data = defaultdict(list)
    for item in all_categories:
        monthly_data[item["月份"]].append(item)
    
    # 月度总览索引
    overview_map = {item["月份"]: item for item in monthly_overview}
    
    # 计算结果
    results = []
    
    for month in ["2026-01", "2026-02", "2026-03"]:
        categories = monthly_data[month]
        overview = overview_map[month]
        
        # 当月品类回收金额总和
        total_category_amount = sum(c["回收金额"] for c in categories)
        
        # 计算各品类估算毛利率
        for cat in categories:
            # 品类占总回收金额的比例
            ratio = cat["回收金额"] / total_category_amount if total_category_amount > 0 else 0
            
            # 估算品类销售额（按比例分摊）
            est_sales = overview["销售额"] * ratio
            
            # 估算品类销售成本（按比例分摊）
            est_cost = overview["销售成本"] * ratio
            
            # 估算品类毛利
            est_profit = est_sales - est_cost
            
            # 估算品类毛利率
            est_margin = (est_profit / est_sales * 100) if est_sales > 0 else 0
            
            results.append({
                "月份": month,
                "品类": cat["品类"],
                "回收量": cat["回收量"],
                "回收金额": cat["回收金额"],
                "回收金额占比": round(ratio * 100, 2),
                "估算销售额": round(est_sales, 2),
                "估算销售成本": round(est_cost, 2),
                "估算毛利": round(est_profit, 2),
                "估算毛利率": round(est_margin, 2),
            })
    
    return results


def print_report(results):
    """打印格式化报表"""
    
    print("=" * 80)
    print("每月品类毛利率估算报表")
    print("=" * 80)
    
    # 按月份分组
    by_month = defaultdict(list)
    for r in results:
        by_month[r["月份"]].append(r)
    
    for month in ["2026-01", "2026-02", "2026-03"]:
        items = by_month[month]
        # 按回收金额排序
        items.sort(key=lambda x: x["回收金额"], reverse=True)
        
        print(f"\n【{month}】")
        print("-" * 80)
        print(f"{'品类':<15} {'回收量':>10} {'回收金额':>15} {'占比':>8} {'估算毛利率':>10}")
        print("-" * 80)
        
        for item in items:
            print(f"{item['品类']:<15} {item['回收量']:>10,} {item['回收金额']:>15,.0f} {item['回收金额占比']:>7.2f}% {item['估算毛利率']:>9.2f}%")
        
        # 月度汇总
        total_amount = sum(i["回收金额"] for i in items)
        total_profit = sum(i["估算毛利"] for i in items)
        total_sales = sum(i["估算销售额"] for i in items)
        avg_margin = (total_profit / total_sales * 100) if total_sales > 0 else 0
        print("-" * 80)
        print(f"{'合计':<15} {'':>10} {total_amount:>15,.0f} {'100.00%':>8} {avg_margin:>9.2f}%")
    
    # Q1汇总
    print("\n" + "=" * 80)
    print("【Q1汇总】")
    print("-" * 80)
    
    # 按品类汇总
    category_summary = defaultdict(lambda: {"回收量": 0, "回收金额": 0, "估算毛利": 0, "估算销售额": 0})
    for r in results:
        cat = r["品类"]
        category_summary[cat]["回收量"] += r["回收量"]
        category_summary[cat]["回收金额"] += r["回收金额"]
        category_summary[cat]["估算毛利"] += r["估算毛利"]
        category_summary[cat]["估算销售额"] += r["估算销售额"]
    
    # 转换为列表并排序
    summary_list = []
    for cat, data in category_summary.items():
        margin = (data["估算毛利"] / data["估算销售额"] * 100) if data["估算销售额"] > 0 else 0
        summary_list.append({
            "品类": cat,
            "回收量": data["回收量"],
            "回收金额": data["回收金额"],
            "估算毛利率": round(margin, 2),
        })
    
    summary_list.sort(key=lambda x: x["回收金额"], reverse=True)
    
    print(f"{'品类':<15} {'Q1回收量':>12} {'Q1回收金额':>18} {'估算毛利率':>10}")
    print("-" * 80)
    
    for item in summary_list:
        print(f"{item['品类']:<15} {item['回收量']:>12,} {item['回收金额']:>18,.0f} {item['估算毛利率']:>9.2f}%")
    
    print("=" * 80)
    print("\n说明：品类毛利率为估算值，基于品类回收金额占比分摊月度总成本计算")
